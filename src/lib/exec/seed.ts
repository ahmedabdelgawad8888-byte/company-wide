function activity(
  id: string,
  ownerId: string,
  clientId: string,
  offset: number,
  type: SalesActivity["type"],
  outcome: CallOutcome | undefined,
  note: string,
): SalesActivity {
  const base: SalesActivity = { id, ownerId, clientId, date: day(offset), type, note };
  return outcome ? { ...base, outcome } : base;
}

export const salesActivities: SalesActivity[] = (() => {
  const rows: SalesActivity[] = [];
  const clients = ["c1", "c2", "c3", "c4", "c5", "c6"];
  const outcomes: CallOutcome[] = ["Answered", "No Answer", "Follow-up Required"];
  let n = 0;
  for (let d = 0; d < 90; d += 1) {
    for (let i = 0; i < salesOwners.length; i += 1) {
      const seedN = (d * 7 + i * 13) % 11;
      if (seedN > 6) continue;
      n += 1;
      const owner = salesOwners[i]!;
      const client = clients[(d + i) % clients.length]!;
      const type: SalesActivity["type"] =
        seedN < 3
          ? "Call"
          : seedN === 3
            ? "Meeting Scheduled"
            : seedN === 4
              ? "Meeting Completed"
              : seedN === 5
                ? "Quotation Requested"
                : "Quotation Sent";
      rows.push(
        activity(
          `xa${n}`,
          owner,
          client,
          -d,
          type,
          type === "Call" ? outcomes[seedN % 3] : undefined,
          type === "Call" ? "Client call logged" : `${type} logged`,
        ),
      );
    }
  }
  return rows;
})();

